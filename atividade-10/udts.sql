-- Criando o tipo de objeto para representar um endereço.

CREATE OR REPLACE TYPE t_endereco AS OBJECT (
    logradouro VARCHAR2(100),
    numero VARCHAR2(10),
    bairro VARCHAR2(50),
    cidade VARCHAR2(50),
    uf VARCHAR2(2),
    cep VARCHAR2(9),

    MEMBER FUNCTION get_endereco_completo
        RETURN VARCHAR2
);
/

-- Implementando o método responsável por formatar o endereço.

CREATE OR REPLACE TYPE BODY t_endereco AS

    MEMBER FUNCTION get_endereco_completo
        RETURN VARCHAR2 IS
    BEGIN
        RETURN logradouro || ', ' || numero ||
               ' - ' || bairro || ', ' ||
               cidade || '/' || uf ||
               ' (CEP: ' || cep || ')';

