-- Criando o tipo de objeto t_retangulo.

CREATE OR REPLACE TYPE t_retangulo AS OBJECT (
    largura NUMBER,
    altura NUMBER,

    MEMBER FUNCTION calcular_area
        RETURN NUMBER,

    MEMBER FUNCTION calcular_perimetro
        RETURN NUMBER
);
/

-- Implementando os métodos de cálculo.

CREATE OR REPLACE TYPE BODY t_retangulo AS

    MEMBER FUNCTION calcular_area
        RETURN NUMBER IS
    BEGIN
        RETURN largura * altura;
    END;

    MEMBER FUNCTION calcular_perimetro
        RETURN NUMBER IS
    BEGIN
        RETURN 2 * (largura + altura);
    END;

END;
/


-- Instanciando um retângulo e testando seus métodos.

SELECT
    t_retangulo(5, 3).calcular_area() AS area,
    t_retangulo(5, 3).calcular_perimetro() AS perimetro
FROM DUAL;

