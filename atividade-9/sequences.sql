-- Criando uma Sequence com CACHE e limites definidos.

CREATE SEQUENCE seq_clientes_id
    START WITH 1000
    INCREMENT BY 1
    MINVALUE 1000
    MAXVALUE 999999
    CACHE 20
    NOCYCLE;


-- NEXTVAL retorna o próximo valor da Sequence.

SELECT seq_clientes_id.NEXTVAL AS proximo_id
FROM DUAL;


-- CURRVAL retorna o último valor utilizado na sessão.

SELECT seq_clientes_id.CURRVAL AS id_atual
FROM DUAL;


-- Avançando novamente a Sequence.

SELECT seq_clientes_id.NEXTVAL AS novo_id
FROM DUAL;


