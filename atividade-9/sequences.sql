/* ============================================================
   EXERCÍCIO 2 - TRIGGER VS DEFAULT
   ============================================================ */

-- Criando uma Sequence para a abordagem tradicional.

CREATE SEQUENCE seq_exemplo_trigger
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;


-- Criando tabela para utilizar a Trigger.

CREATE TABLE tb_exemplo_trigger (
    id NUMBER PRIMARY KEY,
    descricao VARCHAR2(100) NOT NULL
);


-- Trigger responsável por preencher o ID automaticamente.

CREATE OR REPLACE TRIGGER trg_exemplo_trigger
BEFORE INSERT ON tb_exemplo_trigger
FOR EACH ROW
BEGIN
    IF :NEW.id IS NULL THEN
        :NEW.id := seq_exemplo_trigger.NEXTVAL;
    END IF;
END;
/


