   ETAPA 4 - RELACIONAMENTO MESTRE-DETALHE UTILIZANDO CURRVAL
   ============================================================ */

-- Criando a tabela de pedidos relacionada aos clientes.

CREATE TABLE tb_pedidos_apex (
    id_pedido NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente NUMBER NOT NULL,
    data_pedido DATE DEFAULT SYSDATE,
    valor_total NUMBER(10,2) NOT NULL,

    CONSTRAINT fk_ped_cli
        FOREIGN KEY (id_cliente)
        REFERENCES tb_clientes_apex(id_cliente)
);


-- Inserindo um cliente e dois pedidos utilizando PL/SQL.

DECLARE
    v_id_cliente NUMBER;
BEGIN

    INSERT INTO tb_clientes_apex
        (id_cliente, nome_razao, cpf_cnpj, cidade)
    VALUES
        (seq_clientes_id.NEXTVAL,
         'Mega Atacado do Brasil',
         '77.888.999/0001-22',
         'Belo Horizonte')
    RETURNING id_cliente INTO v_id_cliente;


    -- Utilizando CURRVAL para relacionar o primeiro pedido.

    INSERT INTO tb_pedidos_apex
        (id_cliente, valor_total)
    VALUES
        (seq_clientes_id.CURRVAL, 4500.00);


    -- Utilizando a variável para relacionar o segundo pedido.

    INSERT INTO tb_pedidos_apex
        (id_cliente, valor_total)
    VALUES
        (v_id_cliente, 12500.00);


    COMMIT;

END;
/


-- Consultando o relacionamento entre clientes e pedidos.

SELECT
    c.id_cliente,
    c.nome_razao,
    p.id_pedido,
    p.valor_total
FROM tb_clientes_apex c
INNER JOIN tb_pedidos_apex p
    ON c.id_cliente = p.id_cliente
WHERE c.nome_razao = 'Mega Atacado do Brasil';


