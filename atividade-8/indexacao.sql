-- EXERCICIO 1 - SELETIVIDADE E LEADING COLUMN
EXPLAIN PLAN FOR
SELECT nome, salario
FROM tb_funcionarios
WHERE cargo = 'ANALISTA';

SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY);

SELECT nome, salario
FROM tb_funcionarios
WHERE cargo = 'ANALISTA';

-- RESPOSTA:
-- O indice IDX_FUNC_DEP_CARGO_SAL foi criado na ordem DEPARTAMENTO,
-- CARGO e SALARIO. A primeira coluna e a coluna lider (Leading
-- Column). Como a consulta filtra somente por CARGO, sem informar
-- DEPARTAMENTO, o Oracle nao consegue fazer uma busca direta e
-- simples pela faixa de CARGO no indice: os valores estao
-- organizados primeiro por DEPARTAMENTO.
--
-- O otimizador pode considerar alternativas como INDEX SKIP SCAN
-- ou FULL TABLE SCAN, conforme estatisticas, seletividade e custo.
-- Portanto, a ausencia da coluna lider dificulta o uso eficiente
-- do indice, mas nao significa que o Oracle nunca possa utiliza-lo.


